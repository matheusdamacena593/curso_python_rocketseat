# Operadores lógicos

# E lógico (and)
if True and True:
    print("Bloco será executado")

if True and False:
    print("Bloco não será executado")

if False and False:
    print("Bloco não será executado")

# Ou lógico (or)
if True or True:
    print("Bloco será executado")

if False or False:
    print("Bloco não será executado")

if True or False:
    print("Bloco será executado")
# Inteiro
numero_inteiro = 3
print("Inteiro = ", numero_inteiro)

# Real com ponto flutuante
numero_real = 3.14
print("Real com ponto flutuante = ", numero_real)

# Type() -> retorna o tipo da variavel
print("Tipo da variavel inteiro = ", type(numero_inteiro))
print("Tipo da variavel real = ", type(numero_real))

# Soma +
soma = 1 + 1
print("1 + 1 = ", soma)

# Subtração -
subtracao = 1 - 1
print("1 - 1 = ", subtracao)

# Multiplicação *
multiplicacao = 2 * 2
print("2 x 2 = ", multiplicacao)

# Divisão /
divisao = 5 / 2
print("5 / 2 = ", divisao)
print("Tipo da variavel do resultado da divisao = ", type(divisao))

# Int()
print("Valor em inteiro", int(divisao))

# Float()
print("Valor em float", float(divisao))

# Modulo %
modulo = 5 % 2
print("5 % 2 = ", modulo)

# Divisão inteira //
divisao_inteira = 5 // 2
print("5 // 2 = ", divisao_inteira)
